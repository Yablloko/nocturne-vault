"use strict";
const fs=require("node:fs");const {spawn}=require("node:child_process");
const assert=require("node:assert/strict");
const puppeteer=require("puppeteer-core");
const path=require("node:path");
const run=async()=>{
 const chrome=process.env.CHROME_BIN||"/usr/bin/google-chrome";
 const server=spawn("python3",["-m","http.server","8766","--bind","127.0.0.1","--directory","giftvault-v2"],{stdio:"ignore"});
 let browser;
 const sleep=t=>new Promise(r=>setTimeout(r,t));
 try{
  await sleep(1200);
  browser=await puppeteer.launch({executablePath:chrome,headless:true,args:["--no-sandbox","--disable-dev-shm-usage","--disable-gpu"]});
  const desktop=await browser.newPage();await desktop.setViewport({width:1440,height:1024,deviceScaleFactor:1});
  const errors=[];desktop.on("pageerror",e=>errors.push(e.message));
  await desktop.goto("http://127.0.0.1:8766/index.html",{waitUntil:"domcontentloaded"});
  await desktop.waitForSelector(".case-tile",{timeout:10000});
  assert.equal(await desktop.$$eval(".case-tile",xs=>xs.length),4,"Four original case tiles");
  assert.equal(await desktop.$eval(".live-track",x=>getComputedStyle(x).animationName),"marquee","Live ticker is animated");
  await sleep(1700);
  let imgStatus=await desktop.$eval(".case-tile img",x=>({complete:x.complete,width:x.naturalWidth,src:x.src}));
  console.log("MAIN_IMAGE",JSON.stringify(imgStatus));
  const screen=await desktop.screenshot({type:"jpeg",quality:69});
  console.log("SCREENSHOT_DESKTOP_START"+screen.toString("base64")+"SCREENSHOT_DESKTOP_END");
  await desktop.click('[data-open="origin"]');
  await desktop.waitForSelector("#screen-case.active",{timeout:5000});
  assert.equal(await desktop.$$eval("#drops-grid .drop-card",xs=>xs.length),4,"All case drops listed");
  assert.match(await desktop.$eval("#drop-count",x=>x.textContent),/4 GIFTS/);
  await desktop.click("#detail-open");
  await desktop.waitForSelector(".reveal-overlay.show",{timeout:8000});
  await desktop.click("#reveal-inventory");
  assert.equal(await desktop.$$eval(".item-tile",xs=>xs.length),1,"Reward added to inventory");
  await desktop.click('[data-nav="editor"].mobile-tabs button').catch(()=>{});
  await desktop.evaluate(()=>document.querySelector(".desktop-nav [data-nav='editor']")?.click());
  await desktop.waitForSelector("#screen-editor.active");
  await desktop.click("#editor-new");
  await desktop.type("#edit-title","ARCHIVE / ZERO");
  await desktop.$eval("#edit-title",x=>x.value="ARCHIVE / ZERO");
  await desktop.$eval("#edit-desc",x=>x.value="Sample case artwork");
  await desktop.$eval("#edit-price",x=>x.value="375");
  await desktop.select("#edit-active","1");
  await desktop.click("#editor-save");
  await desktop.evaluate(()=>document.querySelector(".desktop-nav [data-nav='home']")?.click());
  await desktop.waitForSelector("#screen-home.active");
  assert.equal(await desktop.$$eval(".case-tile",xs=>xs.length),5,"New published case in home");
  const mobile=await browser.newPage();mobile.on("pageerror",e=>errors.push(e.message));
  await mobile.setViewport({width:390,height:844,deviceScaleFactor:1});
  await mobile.goto("http://127.0.0.1:8766/index.html",{waitUntil:"domcontentloaded"});
  await mobile.waitForSelector(".case-tile");
  await sleep(1700);
  const mobileScroll=await mobile.evaluate(()=>({w:document.documentElement.scrollWidth,inner:window.innerWidth}));
  console.log("MOBILE_WIDTH",JSON.stringify(mobileScroll));
  assert(mobileScroll.w<=mobileScroll.inner+1,"No mobile horizontal overflow");
  const mobileImage=await mobile.screenshot({type:"jpeg",quality:70});
  console.log("SCREENSHOT_MOBILE_START"+mobileImage.toString("base64")+"SCREENSHOT_MOBILE_END");
  assert.deepEqual(errors,[],"No unhandled browser JS errors");
  console.log("UI_SMOKE_ALL_PASSED");
 }finally{if(browser)await browser.close();server.kill("SIGTERM")}
};
run().catch(err=>{console.error(err);process.exitCode=1});
